'use client'

import Link from 'next/link'
import { ArrowLeft, Bot, Home, Info, Maximize2, Minimize2, PanelRightClose, Sparkles, X } from 'lucide-react'
import { useEffect, useState } from 'react'
import type { AssistantView } from '@/types/assistant'
import { useAssistant } from './assistant-provider'
import { ChatView } from './chat-view'
import { HelpView } from './help-view'
import { HomeView } from './home-view'
import { SummaryView } from './summary-view'

const VIEW_TITLE: Record<Exclude<AssistantView, 'home'>, string> = {
  summary: 'Summary',
  help: 'Help',
  talk: 'Talk',
  teach: 'Teach',
}

/**
 * The assistant panel, laid out like the reference: a dark header with the
 * avatar, title and info / expand / close controls, a sub-row with Replay
 * Greeting, the four action cards, and a footer with the item count.
 */
export function AssistantPanel({ onClose }: { onClose: () => void }) {
  const view = useAssistant(state => state.view)
  const itemCount = useAssistant(state => state.approvals.length)
  const goHome = useAssistant(state => state.goHome)
  const loadGreeting = useAssistant(state => state.loadGreeting)
  const replayGreeting = useAssistant(state => state.replayGreeting)
  const abortAll = useAssistant(state => state.abortAll)

  // pure UI state: only this component cares about it
  const [minimized, setMinimized] = useState(false)
  const [expanded, setExpanded] = useState(false)
  const [infoOpen, setInfoOpen] = useState(false)

  useEffect(() => {
    void loadGreeting()
  }, [loadGreeting])

  if (minimized) {
    return <button type="button" className="cb-pill" onClick={() => setMinimized(false)}>
      <span className="cb-avatar small"><Bot size={16} aria-hidden="true" /></span>
      <span>Crystal Ball Assistant</span>
      <span className="cb-online" aria-hidden="true" />
    </button>
  }

  const close = () => {
    abortAll() // no request keeps running (or spending) once the panel is closed
    onClose()
  }

  return <section className={`cb-panel${expanded ? ' expanded' : ''}`} aria-label="Crystal Ball Assistant">
    <header className="cb-header">
      <div className="cb-avatar"><Sparkles size={18} aria-hidden="true" /></div>
      <div className="cb-title"><h2>Approvals</h2><span>Crystal Ball Assistant</span></div>
      <button type="button" className="cb-icon-button" aria-label="About this assistant" aria-expanded={infoOpen} onClick={() => setInfoOpen(open => !open)}><Info size={16} aria-hidden="true" /></button>
      <button type="button" className="cb-icon-button" aria-label={expanded ? 'Shrink assistant' : 'Expand assistant'} onClick={() => setExpanded(value => !value)}>{expanded ? <Minimize2 size={16} aria-hidden="true" /> : <Maximize2 size={16} aria-hidden="true" />}</button>
      <button type="button" className="cb-icon-button" aria-label="Minimize assistant" onClick={() => setMinimized(true)}><PanelRightClose size={16} aria-hidden="true" /></button>
      <button type="button" className="cb-icon-button" aria-label="Close assistant" onClick={close}><X size={16} aria-hidden="true" /></button>
    </header>
    {infoOpen && <p className="cb-info">Answers are generated by an AI model and can be wrong. Check anything important before you act on it.</p>}

    <div className="cb-subheader">
      {view === 'home'
        ? <span className="cb-crumb"><Home size={14} aria-hidden="true" /> Approvals</span>
        : <button type="button" className="cb-back" aria-label="Back to actions" onClick={goHome}><ArrowLeft size={14} aria-hidden="true" /> {VIEW_TITLE[view]}</button>}
      <button type="button" className="cb-link-button" onClick={() => { goHome(); void replayGreeting() }}>Replay Greeting</button>
    </div>

    <div className="cb-body">
      {view === 'home' && <HomeView />}
      {view === 'summary' && <SummaryView />}
      {view === 'help' && <HelpView />}
      {(view === 'talk' || view === 'teach') && <ChatView key={view} mode={view} />}
    </div>

    <footer className="cb-footer">
      <span>{itemCount} {itemCount === 1 ? 'item' : 'items'}</span>
      <Link href="/approvals/new">New approval</Link>
    </footer>
  </section>
}
